type Artifact struct {
	URL    string `yaml:"url" json:"url"`
	SHA256 string `yaml:"sha256" json:"sha256"`
	// Extract is the path of the binary inside the downloaded archive, if any.
	Extract string `yaml:"extract,omitempty" json:"extract,omitempty"`
}

// EditedError means a lock's content digest is missing (written by a
// release before content digests, or removed) or doesn't match what the
// lock holds: it was edited by hand. Read returns the lock with it, for
// the caller that re-resolves every input; every other refuses the lock.
type EditedError struct {
	Path    string
	Missing bool
}

func (e *EditedError) Error() string {
	name := filepath.Base(e.Path)
	if e.Missing {
		return name + " has no contentDigest (it was written by an older clearcutt-factory, or edited by hand); run clearcutt-factory lock to write one"
	}
	return name + " was edited by hand (its contentDigest doesn't match its content); run clearcutt-factory lock --update to re-resolve it, or restore it from version control"
}

// NewerError means a lock was written by a newer clearcutt-factory than
// the one reading it.
type NewerError struct {
	Path, Generator, Version string
	// Cause is the decoding error, when the lock couldn't even be read.
	Cause error
}

func (e *NewerError) Error() string {
	msg := fmt.Sprintf("%s was written by %s, newer than this clearcutt-factory (%s); upgrade clearcutt-factory, or re-lock with this version", filepath.Base(e.Path), e.Generator, e.Version)
	if e.Cause != nil {
		msg += fmt.Sprintf(" (%v)", e.Cause)
	}
	return msg
}

func (e *NewerError) Unwrap() error { return e.Cause }

// Read loads a lockfile without checking which release wrote it.
func Read(path string) (*Lock, error) { return ReadFor(path, "") }

// ReadFor loads a lockfile for the clearcutt-factory of version ("" to
// skip that check). A lock a newer minor release wrote is refused
// (*NewerError), as is one this version can't decode when any newer
// release wrote it. A lock whose content digest is missing or wrong is
// returned with an *EditedError.
func ReadFor(path, version string) (*Lock, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	// What wrote it, read leniently: the strict decode below may fail on
	// fields this version doesn't know.
	var head struct {
		Generator string `yaml:"generator"`
	}
	_ = yaml.Unmarshal(b, &head)
	if version != "" && newer(head.Generator, version, true) {
		return nil, &NewerError{Path: path, Generator: head.Generator, Version: version}
	}
	var l Lock
	dec := yaml.NewDecoder(bytes.NewReader(b))
	dec.KnownFields(true)
	if err := dec.Decode(&l); err != nil {
		if version != "" && newer(head.Generator, version, false) {
			return nil, &NewerError{Path: path, Generator: head.Generator, Version: version, Cause: err}
		}
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if l.APIVersion != manifest.APIVersion || l.Kind != Kind {
		return nil, fmt.Errorf("%s: expected apiVersion %q and kind %q", path, manifest.APIVersion, Kind)
	}
	switch {
	case l.ContentDigest == "":
		return &l, &EditedError{Path: path, Missing: true}
	case l.ContentDigest != l.contentDigest():
		return &l, &EditedError{Path: path}
	}
	return &l, nil
}

// IsEdited reports whether err is an EditedError, and whether the digest
// was merely missing (an older lock) rather than wrong.
func IsEdited(err error) (edited, missing bool) {
	var e *EditedError
	if errors.As(err, &e) {
		return true, e.Missing
	}
	return false, false
}

var releaseRE = regexp.MustCompile(`\bv(\d+)\.(\d+)\.(\d+)\b`)

// Generator is the generator field for a clearcutt-factory of version.
func Generator(version string) string {
	return GeneratorName + " " + version
}

// newer reports whether generator names a release later than version,
// comparing major and minor only with minorOnly (patch releases keep the
// format). Development builds on either side compare as not newer.
func newer(generator, version string, minorOnly bool) bool {
	g, v := releaseRE.FindStringSubmatch(generator), releaseRE.FindStringSubmatch(version)
	if g == nil || v == nil {
		return false
	}
	n := 4
	if minorOnly {
		n = 3
	}
	for i := 1; i < n; i++ {
		a, _ := strconv.Atoi(g[i])
		b, _ := strconv.Atoi(v[i])
		if a != b {
			return a > b
		}
	}
	return false
}

// Marshal renders the lockfile deterministically, as it is.
func (l *Lock) Marshal() []byte {
	var buf bytes.Buffer
	buf.WriteString(header)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	_ = enc.Encode(l)
	return buf.Bytes()
}

// Content renders the lock's pins: everything but which release wrote it
// and the content digest, so two locks compare by what they pin.
func (l *Lock) Content() []byte {
	c := *l
	c.Generator, c.ContentDigest = "", ""
	return c.Marshal()
}

// contentDigest is the sha256 of the lock as written, with ContentDigest
// itself left out.
func (l *Lock) contentDigest() string {
	c := *l
	c.ContentDigest = ""
	sum := sha256.Sum256(c.Marshal())
	return "sha256:" + hex.EncodeToString(sum[:])
}

// Write saves the lockfile, with its content digest, atomically: the file
// holds the old lock or the new one, never part of either.
func (l *Lock) Write(path string) error {
	l.ContentDigest = l.contentDigest()
	return WriteFileAtomic(path, l.Marshal(), 0o644)
}

// WriteFileAtomic writes data to a temporary file beside path and renames
// it over path, so a crash or a failed write leaves the old file intact.
func WriteFileAtomic(path string, data []byte, perm os.FileMode) error {
	dir, base := filepath.Split(path)
	tmp, err := os.CreateTemp(dir, "."+base+".*")
	if err != nil {
		return err
	}
	name := tmp.Name()
	clean := func(err error) error {
		_ = tmp.Close()
		_ = os.Remove(name)
		return err
	}
	if _, err := tmp.Write(data); err != nil {
		return clean(err)
	}
	if err := tmp.Chmod(perm); err != nil {
		return clean(err)
	}
	if err := tmp.Close(); err != nil {
		_ = os.Remove(name)
		return err
	}
	if err := os.Rename(name, path); err != nil {
		_ = os.Remove(name)
		return err
	}
	return nil
}

// Tool returns the locked entry for name.
func (l *Lock) Tool(name string) *Tool {
	for i := range l.Tools {
		if l.Tools[i].Name == name {
			return &l.Tools[i]
		}
	}
	return nil
}

// Inputs is everything in the manifest and org profile that affects resolution.
// Changing any of it makes the lock stale.
type Inputs struct {
	Base           string          `json:"base"`
	Platforms      []string        `json:"platforms"`
	PackageManager string          `json:"packageManager,omitempty"`
	Repositories   []string        `json:"repositories"`
	Packages       []string        `json:"packages"`
	Tools          []manifest.Tool `json:"tools"`
	BuildKit       string          `json:"buildkit"`
	Frontend       string          `json:"frontend"`
	Toolbox        string          `json:"toolbox"`
	// Apps: the stack's build image and definition.
	Build string `json:"build,omitempty"`
	Stack string `json:"stack,omitempty"`
}

func InputsOf(m *manifest.Manifest, o *manifest.Org) Inputs {
	in := Inputs{
		Base:           m.Spec.Base,
		Platforms:      m.Spec.Platforms,
		PackageManager: m.Spec.PackageManager,
		Repositories:   m.Spec.Repositories,
		Packages:       m.Spec.Packages,
		Tools:          m.Spec.Tools,
		BuildKit:       o.Builder.BuildKit,
		Frontend:       o.Builder.Frontend,
		Toolbox:        o.Builder.Toolbox,
	}
	if m.Stack != nil {
		in.Build = m.Stack.BuildRef
		in.Stack = StackDigest(m.Stack)
	}
	return in
}

// StackDigest identifies a stack definition. The smoke test doesn't shape
// the image, so changing it doesn't make locks stale.
func StackDigest(s *manifest.Stack) string {
	spec := s.Spec
	spec.Test = nil
	return Digest(struct {
		Name string
		Spec manifest.StackSpec
	}{s.Metadata.Name, spec})
}

func (in Inputs) Digest() string { return Digest(in) }

// Digest hashes the JSON encoding of v.
func Digest(v any) string {
	b, err := json.Marshal(v)
	if err != nil {
		panic(err)
	}
	sum := sha256.Sum256(b)
	return "sha256:" + hex.EncodeToString(sum[:])
}
